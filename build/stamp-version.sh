#!/usr/bin/env bash
# Stamps the release tag into the binary so the running app reports the version
# it was built from — the self-updater compares the latest release tag against
# it. Called by .github/workflows/build.yml before each platform build;
# development builds keep the committed default in Services/Updater/updater.go.
set -euo pipefail

tag="${1:?usage: stamp-version.sh <tag>}"
version="${tag#v}"

printf 'package Updater\n\n// Code generated by build/stamp-version.sh. DO NOT EDIT.\n\nfunc init() { Version = "%s" }\n' \
	"$version" > Services/Updater/version_stamped.go

echo "argus: stamped Services/Updater/version_stamped.go with version ${version}"
